'use strict';
const fs = require('node:fs'), path = require('node:path');
const root = path.resolve(__dirname, '..');
function generated() {
  const cards = require('../src/data/tarot.js');
  if (cards.length !== 78 || cards.some((card, index) => card.id !== index)) throw Error('TRNG_CARD_CATALOG_INVALID');
  const project = 'IoT-Firmware/CIBYP-TRNG/';
  return {
    [project + 'web/catalog.json']: JSON.stringify(cards) + '\n',
    [project + 'rust/core/src/catalog.rs']: '// Generated by scripts/build-trng-catalog.cjs from src/data/tarot.js. Do not edit.\n' +
      'pub const CARDS: [&str; 78] = [\n' + cards.map(card => '    ' + JSON.stringify(JSON.stringify(card).slice(0, -1)) + ',').join('\n') + '\n];\n',
  };
}
function catalog(check = false) {
  for (const [file, content] of Object.entries(generated())) {
    const target = path.join(root, file);
    if (check) { if (fs.readFileSync(target, 'utf8') !== content) throw Error('TRNG_CATALOG_STALE: ' + file); }
    else { fs.mkdirSync(path.dirname(target), {recursive:true}); fs.writeFileSync(target, content); }
  }
}
if (require.main === module) catalog(process.argv.includes('--check'));
module.exports = {catalog};
