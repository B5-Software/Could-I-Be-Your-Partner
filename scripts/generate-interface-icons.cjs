'use strict';
// Reproducible, rotationally symmetric gear. No hand-positioned teeth.
const fs = require('node:fs');
const path = require('node:path');
const points = [];
for (let tooth = 0; tooth < 8; tooth++) {
  for (const [angle, radius] of [
    [-22.5, 7.8],
    [-13, 7.8],
    [-9, 10],
    [9, 10],
    [13, 7.8],
    [22.5, 7.8],
  ]) {
    const radians = ((tooth * 45 + angle) * Math.PI) / 180;
    points.push(
      `${(12 + Math.cos(radians) * radius).toFixed(3)} ${(12 + Math.sin(radians) * radius).toFixed(3)}`,
    );
  }
}
const shape = `<path d="M${points.join('L')}Z"/><circle cx="12" cy="12" r="3.2"/>`;
const destination = path.resolve(__dirname, '../src/renderer/core/generated-shell-icons.ts');
const source =
  '/* SPDX-License-Identifier: GPL-3.0-or-later; Generated by scripts/generate-interface-icons.cjs */\n// prettier-ignore\nexport const SETTINGS_ICON = ' +
  JSON.stringify(shape) +
  ';\n';
if (!fs.existsSync(destination) || fs.readFileSync(destination, 'utf8') !== source)
  fs.writeFileSync(destination, source);
