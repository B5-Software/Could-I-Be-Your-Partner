const assert = require('node:assert/strict');
module.exports = async function checkMcp(webContents) {
  const result = await webContents.executeJavaScript(`(async () => {
    const wait = async fn => { const end = Date.now()+4000; while (!await fn()) { if(Date.now()>end) throw Error('MCP UI timeout: '+ fn.toString() + ' ' + document.getElementById('mcp-servers-list').textContent.trim()); await new Promise(r=>setTimeout(r,20)); } };
    const check = (v,m) => { if(!v) throw Error(m); };
    window.navigatePage('settings'); window.activateSettingsTab('mcp');
    await window.api.mcpAddServer({name:'editable',command:'node',args:['before'],env:{TEST:'original'},cwd:'',autoConnect:false});
    // Navigate again to load the list through the settings page's real loader.
    window.navigatePage('chat'); window.navigatePage('settings'); window.activateSettingsTab('mcp');
    await wait(()=>document.querySelector('.btn-mcp-edit[data-name="editable"]'));
    document.querySelector('.btn-mcp-edit[data-name="editable"]').click();
    check(document.getElementById('mcp-new-args').value === '["before"]','original arguments not loaded');
    document.getElementById('mcp-new-name').value = 'edited';
    document.getElementById('mcp-new-args').value = '["after", "two words"]';
    document.getElementById('mcp-new-env').value = '{"TEST":"changed"}';
    document.getElementById('btn-mcp-save').click();
    await wait(()=>document.getElementById('mcp-add-form').classList.contains('hidden') && !document.getElementById('btn-mcp-save').disabled);
    const servers = await window.api.mcpListServers();
    const saved = servers.find(s=>s.name === 'edited');
    check(saved && saved.args[1] === 'two words' && saved.env.TEST === 'changed' && servers.length === 1,'edit added a duplicate or lost configuration');
    await wait(()=>document.querySelector('.btn-mcp-edit[data-name="edited"]'));
    document.querySelector('.btn-mcp-edit[data-name="edited"]').click();
    document.getElementById('mcp-new-type').value = 'http';
    document.getElementById('mcp-new-type').dispatchEvent(new Event('change'));
    check(!document.getElementById('mcp-new-url').closest('.setting-item').classList.contains('hidden'),'HTTP fields hidden');
    document.getElementById('mcp-new-url').value = 'https://example.com/mcp';
    document.getElementById('mcp-new-headers').value = '{"Authorization":"Bearer test"}';
    document.getElementById('btn-mcp-save').click();
    await wait(()=>document.getElementById('mcp-add-form').classList.contains('hidden') && !document.getElementById('btn-mcp-save').disabled);
    const http = (await window.api.mcpListServers())[0];
    check(http.type === 'http' && http.headers.Authorization === 'Bearer test','HTTP change not saved');
    document.querySelector('.btn-mcp-edit').click();
    document.getElementById('mcp-new-name').value = 'cancelled';
    document.getElementById('btn-mcp-cancel').click();
    check((await window.api.mcpListServers())[0].name === 'edited','cancel saved configuration');
    check(document.getElementById('mcp-new-headers').value === '', 'closed draft kept credentials');
    await window.api.mcpRemoveServer('edited');
    await window.api.mcpAddServer({name:'progress', command:'node', args:['-e','process.stdin.on("end",()=>process.exit(0));process.stdin.resume()']});
    const connecting = window.api.mcpConnect('progress');
    await wait(()=>document.querySelector('.mcp-server-card[data-name="progress"] progress'));
    check(document.querySelector('.mcp-server-card[data-name="progress"] progress').value > 0, 'missing connection progress');
    document.querySelector('.mcp-server-card[data-name="progress"] .btn-mcp-disconnect').click();
    check(!(await connecting).ok, 'cancel did not settle connect');
    await wait(async()=> (await window.api.mcpListServers()).find(s=>s.name === 'progress').status === 'disconnected');
    await window.api.mcpUpdateServer('progress',{command:'cibyp-mcp-test-command-does-not-exist',args:[]});
    await window.api.mcpConnect('progress');
    await wait(()=>document.querySelector('.mcp-server-card[data-name="progress"] .mcp-connection-error'));
    check(document.querySelector('.mcp-connection-error').textContent.includes('ENOENT'),'missing connection error');
    await window.api.mcpRemoveServer('progress');
    return {ok:true,checks:['edit and rename','preserved JSON fields','transport switching','cancel clears draft']};
  })()`);
  assert.equal(result.ok, true);
  return result;
};
