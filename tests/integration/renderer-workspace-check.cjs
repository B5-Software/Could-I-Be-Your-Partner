/* Native Chromium checks: real layout, animation cancellation, focus and persistent global state. */
module.exports = async function checkWorkspace(webContents) {
  return webContents.executeJavaScript(`(async () => {
    const check = (condition, message) => { if (!condition) throw new Error(message); };
    // Chromium pauses CSS timelines in hidden windows. Finish their actual animations
    // after the delay so we can validate completion/cancellation without showing a window.
    const wait = async ms => {
      await new Promise(resolve => setTimeout(resolve, ms));
      {
        document.getAnimations().forEach(animation => { if (animation.playState === 'running') animation.finish(); });
        await new Promise(resolve => setTimeout(resolve, 0));
      }
    };
    const until = async check => { for (let n = 0; n < 100; n++) { if (check()) return; await wait(20); } throw new Error('Todo persistence did not reach the UI'); };
    const click = selector => { const element = document.querySelector(selector); check(element, selector); element.click(); };
    const root = document.getElementById('todo-panel');
    const input = document.getElementById('todo-input');
    const manager = window.__sessionManager;
    const primary = manager.getActive('chat');
    check(primary, 'active Chat session');
    document.documentElement.dataset.animations = 'on';
    const main = document.getElementById('main-content');
    const fullWidth = main.getBoundingClientRect().width;
    const leftEdge = main.getBoundingClientRect().left;
    const navLeft = document.getElementById('sidebar').getBoundingClientRect().left;
    const fixedLeft = () => {
      check(Math.abs(main.getBoundingClientRect().left - leftEdge) < 1, 'Todo must keep the conversation left edge fixed');
      check(Math.abs(document.getElementById('sidebar').getBoundingClientRect().left - navLeft) < 1, 'Todo focus must never scroll the left navigation');
      check(document.scrollingElement.scrollLeft === 0 && document.getElementById('app').scrollLeft === 0, 'Todo must never horizontally scroll the workspace');
    };
    click('#btn-todo-sidebar');
    fixedLeft();
    const opening = root.getAnimations().find(animation => animation.effect.getKeyframes().some(frame => 'marginRight' in frame));
    check(opening, 'Todo workspace and sidebar share an animation timeline');
    opening.pause();
    opening.currentTime = 0;
    const startWidth = main.getBoundingClientRect().width;
    opening.currentTime = 90;
    fixedLeft();
    const middleWidth = main.getBoundingClientRect().width;
    check(Math.abs(root.getBoundingClientRect().left - main.getBoundingClientRect().right) < 1, 'sidebar edge tracks the conversation throughout its slide');
    opening.currentTime = 180;
    fixedLeft();
    const endWidth = main.getBoundingClientRect().width;
    check(Math.abs(startWidth - fullWidth) < 1 && middleWidth < startWidth && middleWidth > endWidth, 'conversation width changes continuously with the sidebar');
    opening.finish();
    await wait(240);
    fixedLeft();
    check(root.parentElement.id === 'app' && root.tagName === 'ASIDE', 'Todo must be a workspace sidebar');
    check(getComputedStyle(root).position === 'relative', 'Todo must participate in workspace layout');
    const panelBounds = root.getBoundingClientRect();
    const mainBounds = main.getBoundingClientRect();
    check(mainBounds.width < fullWidth - 200 && mainBounds.right <= panelBounds.left + 1, 'Todo reserves space without covering the conversation');
    check(Math.abs(panelBounds.height - root.parentElement.getBoundingClientRect().height) < 1, 'Todo fills the workspace height');
    const inputBounds = input.getBoundingClientRect();
    const addBounds = document.getElementById('btn-add-todo').getBoundingClientRect();
    check(Math.abs(inputBounds.height - addBounds.height) < 1 && Math.abs(inputBounds.top - addBounds.top) < 1, 'Todo input and add button are aligned');
    check(!root.inert && document.activeElement === input, 'Todo open restores interactivity and focus');
    input.value = '<img src=x onerror=alert(1)> small goal';
    document.getElementById('todo-form').requestSubmit();
    await until(() => primary.agent.todoItems.length === 1);
    check(primary.agent.todoItems.length === 1, 'form persists the global list');
    check(!root.querySelector('.todo-list img'), 'Todo content is rendered as plain text');
    click('[data-todo-action="edit"]');
    const editor = root.querySelector('.todo-edit-input');
    editor.value = 'edited goal';
    editor.form.requestSubmit();
    await until(() => primary.agent.todoItems[0].text === 'edited goal');
    click('[data-todo-action="toggle"]');
    await until(() => primary.agent.todoItems[0].done);
    click('[data-todo-filter="pending"]');
    check(root.querySelectorAll('.todo-item').length === 0, 'pending filter excludes completed items');
    click('[data-todo-filter="all"]');
    input.value = 'draft in first session';
    const otherAgent = new primary.agent.constructor();
    otherAgent.settings = primary.agent.settings;
    otherAgent.workspacePath = primary.agent.workspacePath;
    otherAgent.conversationId = 'ui-second-session';
    otherAgent.conversationTitle = '第二个会话';
    const other = manager.registerAgent('chat', otherAgent);
    manager.activate('chat', other.key);
    check(input.value === 'draft in first session' && root.querySelectorAll('.todo-item').length === 1, 'Todos and drafts persist across sessions');
    input.value = 'second goal';
    document.getElementById('todo-form').requestSubmit();
    await until(() => otherAgent.todoItems.length === 2);
    check(primary.agent.todoItems.length === 2, 'all Agents share the persistent list');
    manager.activate('chat', primary.key);
    check(input.value === '', 'persisting an added todo clears the shared draft');
    check(root.querySelector('.todo-text').textContent === 'edited goal', 'switching back restores the list');
    click('#btn-clear-completed');
    await until(() => primary.agent.todoItems.length === 1);
    check(otherAgent.todoItems[0].text === 'second goal', 'clear completed preserves unfinished global todos');
    primary.agent.clearContextOnly();
    check(primary.agent.todoItems.length === 1, 'clearing a conversation must not clear global todos');
    // Closing and immediately reopening must cancel the stale completion callback.
    click('#btn-close-todo');
    fixedLeft();
    click('#btn-todo-sidebar');
    fixedLeft();
    await wait(240);
    check(!root.classList.contains('hidden') && !root.inert, 'stale Todo exit cannot hide a reopened sidebar');
    click('#btn-close-todo');
    const closing = root.getAnimations().find(animation => animation.effect.getKeyframes().some(frame => 'marginRight' in frame));
    check(closing, 'Todo closes on the same reserved-space timeline');
    closing.pause();
    const closeStartWidth = main.getBoundingClientRect().width;
    closing.currentTime = 90;
    fixedLeft();
    check(main.getBoundingClientRect().width > closeStartWidth && main.getBoundingClientRect().width < fullWidth, 'closing expands only the conversation right edge continuously');
    check(Math.abs(root.getBoundingClientRect().left - main.getBoundingClientRect().right) < 1, 'closing sidebar stays aligned with the conversation right edge');
    closing.finish();
    await wait(240);
    check(root.classList.contains('hidden') && root.inert, 'closed Todo is removed from keyboard navigation');
    fixedLeft();
    check(document.activeElement.id === 'btn-todo-sidebar', 'closing returns keyboard focus');
    check(Math.abs(main.getBoundingClientRect().width - fullWidth) < 1, 'closing Todo returns its workspace space');
    check(!document.getElementById('btn-sidebar-toggle') && !document.getElementById('sidebar').classList.contains('expanded'), 'left navigation stays compact');
    check(!document.querySelector('#main-content .page-dismiss'), 'primary pages have no redundant close buttons');
    check(!document.querySelector('#page-tools [data-settings-open]'), 'Tools has no settings entry button');
    const permissions = document.getElementById('computer-permissions-card');
    check(permissions.previousElementSibling.id === 'tool-auth-section', 'computer permissions are below all tool cards');
    check(parseFloat(getComputedStyle(permissions).marginTop) >= 16, 'computer permission card has vertical spacing');
    const fillers = ['about', 'skills'].map(name => {
      const page = document.getElementById('page-' + name);
      const filler = document.createElement('div');
      filler.style.cssText = 'height:2400px;flex-shrink:0';
      page.appendChild(filler);
      return filler;
    });
    window.navigatePage('about');
    const about = document.getElementById('page-about');
    about.scrollTop = 200;
    check(about.scrollTop === 200 && getComputedStyle(about).overflowY === 'auto', 'primary page has no independent scroller');
    window.navigatePage('skills');
    const skills = document.getElementById('page-skills');
    check(skills.scrollTop === 0, 'next page inherited scrolling');
    skills.scrollTop = 200;
    window.navigatePage('about');
    check(about.scrollTop === 0, 'returning to a primary page retains scrolling');
    fillers.forEach(filler => filler.remove());
    window.navigatePage('about');
    check(document.querySelectorAll('#main-content > .page.active').length === 1, 'navigation has one active page');
    check(document.getElementById('page-chat').inert, 'inactive pages cannot receive focus');
    click('.nav-item[data-page="about"]');
    check(document.getElementById('page-chat').classList.contains('active'), 'clicking an expanded auxiliary app returns to the session');
    for (const page of ['tools','skills','knowledge','memory','automation','history','settings','about']) window.navigatePage(page);
    window.navigatePage('chat');
    await wait(400);
    check(document.getElementById('page-chat').classList.contains('active'), 'late loaders cannot reactivate a previous page');
    window.initCanvas();
    check(document.body.classList.contains('geogebra-open'), 'opening dock allocates workspace space');
    window.minimizePanel('canvas-panel');
    window.restorePanel('canvas-panel');
    await wait(240);
    check(!document.getElementById('canvas-panel').classList.contains('hidden'), 'rapid dock restore cancels stale exits');
    window.initSpreadsheet('native check');
    await wait(240);
    check(document.getElementById('canvas-panel').classList.contains('hidden'), 'dock apps are mutually exclusive');
    check(document.querySelector('[data-panel-id="canvas-panel"]'), 'switching dock retains the previous app as a restore tab');
    window.setAppPanelOpen('spreadsheet-panel', false);
    check(!document.body.classList.contains('geogebra-open'), 'closing active dock releases layout');
    click('[data-panel-id="canvas-panel"]');
    window.setAppPanelOpen('canvas-panel', false);
    await wait(240);
    check(!document.querySelector('[data-panel-id="canvas-panel"]'), 'closing restored app removes its minimized tab');
    document.documentElement.dataset.animations = 'off';
    click('#btn-todo-sidebar');
    click('#btn-close-todo');
    check(root.classList.contains('hidden'), 'disabled animation closes immediately');
    // Native pane/layout behavior is exercised by codeoss-desktop.cjs.
    check(document.getElementById('codeoss-viewport'), 'Code page exposes a native workbench viewport');
    check(document.getElementById('code-agent-panel') && !document.getElementById('code-agent-runtime'), 'CIBYP owns an independent AI sidebar');
    check(typeof window.api.codeOSSOpen === 'function', 'native workbench uses the isolated preload bridge');
    document.documentElement.dataset.animations = 'on';
    window.navigatePage('settings');
    window.activateSettingsTab('overview');
    await wait(200);
    const overview = document.getElementById('settings-overview-cards');
    check(overview.children.length === 6, 'overview cards are hydrated');
    check(overview.getBoundingClientRect().top - overview.previousElementSibling.getBoundingClientRect().bottom >= 12, 'overview description has space before cards');
    check([...overview.children].every(card => card.getBoundingClientRect().height <= 70), 'overview cards stay compact');
    window.activateSettingsTab('animations');
    check(document.querySelector('.settings-panel[data-tab="animations"]').getAttribute('aria-hidden') === 'false', 'settings tabs share accessible activation');
    window.navigatePage('chat');
    return { todo: 'sidebar, aligned input, editable, safe text, persistent across sessions', panels: 'cancelled exits, exclusive docks, navigation, focus, independent scrolling' };
  })()`);
};
